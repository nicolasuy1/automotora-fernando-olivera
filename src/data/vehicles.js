export function getVehicleBySlug(slug) {
  return vehicles.find((vehicle) => vehicle.slug === slug);
}

export function getRelatedVehicles(vehicle) {
  return vehicles
    .filter((item) => item.slug !== vehicle.slug && (item.type === vehicle.type || item.category === vehicle.category))
    .slice(0, 3);
}
